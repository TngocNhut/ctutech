COMMENT ON COLUMN "KhoHang"."TenKhoHang" IS 'Tên kho hoặc bãi để nhận biết trên màn hình vận hành.';
COMMENT ON COLUMN "KhoHang"."LoaiKho" IS 'KHO hoặc BAI, dùng để phân loại địa điểm lưu hàng.';
COMMENT ON COLUMN "KhoHang"."DiaChi" IS 'Địa chỉ vận hành của kho. Có thể để trống.';
COMMENT ON COLUMN "KhoHang"."DangHoatDong" IS 'Cho phép kho nhận đơn mới. Ngừng kho vẫn giữ tồn và lịch sử cũ.';
