-- BẢNG BienDongKho | Nhóm Kho và bãi
-- Số cột: 12 | Khóa chính: MaBienDongKho
-- Vai trò: Sổ nhập, xuất, giữ, nhả giữ, chuyển kho và nhập lại hàng trả.
-- Hoạt động: Ghi biến động cùng lần cập nhật số dư để đối chiếu nhập, xuất và lượng giữ.
-- Tham chiếu tới:
--   - [N-1] BienDongKho.MaChiTietTraHang -> ChiTietTraHang.MaChiTietTraHang
--   - [N-1] BienDongKho.MaDonHang -> DonHang.MaDonHang
--   - [N-1] BienDongKho.(MaKhoHang, MaBienThe) -> TonKho.(MaKhoHang, MaBienThe)
--   - [N-1] BienDongKho.MaNguoiThucHien -> NguoiDung.MaNguoiDung
-- Được tham chiếu bởi: không có.
CREATE TABLE "BienDongKho" (
    "MaBienDongKho" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MaKhoHang" bigint NOT NULL,
    "MaBienThe" bigint NOT NULL,
    "MaDonHang" bigint REFERENCES "DonHang" ON DELETE RESTRICT,
    "MaChiTietTraHang" bigint REFERENCES "ChiTietTraHang" ON DELETE RESTRICT,
    "MaNguoiThucHien" bigint REFERENCES "NguoiDung" ON DELETE RESTRICT,
    "LoaiBienDong" varchar(20) NOT NULL,
    "ThayDoiTon" integer NOT NULL,
    "ThayDoiGiu" integer NOT NULL DEFAULT 0,
    "KhoaChongLap" varchar(100) NOT NULL,
    "GhiChu" varchar(500),
    "NgayTao" timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY ("MaKhoHang", "MaBienThe") REFERENCES "TonKho" ON DELETE RESTRICT,
    UNIQUE ("MaKhoHang", "MaBienThe", "KhoaChongLap"),
    CHECK (
        ("LoaiBienDong" = 'SO_DU_DAU' AND "ThayDoiTon" > 0 AND "ThayDoiGiu" BETWEEN 0 AND "ThayDoiTon")
        OR ("LoaiBienDong" IN ('NHAP', 'NHAP_HANG_TRA', 'CHUYEN_DEN') AND "ThayDoiTon" > 0 AND "ThayDoiGiu" = 0)
        OR ("LoaiBienDong" = 'CHUYEN_DI' AND "ThayDoiTon" < 0 AND "ThayDoiGiu" = 0)
        OR ("LoaiBienDong" = 'DIEU_CHINH' AND "ThayDoiTon" <> 0 AND "ThayDoiGiu" = 0)
        OR ("LoaiBienDong" = 'GIU_HANG' AND "ThayDoiTon" = 0 AND "ThayDoiGiu" > 0)
        OR ("LoaiBienDong" = 'TRA_GIU' AND "ThayDoiTon" = 0 AND "ThayDoiGiu" < 0)
        OR ("LoaiBienDong" = 'XUAT_DON' AND "ThayDoiTon" < 0 AND "ThayDoiTon" = "ThayDoiGiu")
    ),
    CHECK ("LoaiBienDong" NOT IN ('GIU_HANG', 'TRA_GIU', 'XUAT_DON', 'NHAP_HANG_TRA') OR "MaDonHang" IS NOT NULL),
    CHECK (("MaChiTietTraHang" IS NOT NULL) = ("LoaiBienDong" = 'NHAP_HANG_TRA'))
);
