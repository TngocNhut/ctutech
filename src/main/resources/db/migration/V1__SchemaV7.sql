    "DangHoatDong" boolean NOT NULL DEFAULT true,
    "NgayTao" timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE "KhoHang" IS 'Kho hoặc bãi có thể cấp hàng. Ngừng hoạt động thay cho xóa khi còn dữ liệu lịch sử.';
